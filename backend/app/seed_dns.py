from __future__ import annotations

import time
from datetime import datetime, timedelta, timezone
from typing import Any

_BASE_NOW = time.time()
_BASE_DT = datetime.fromtimestamp(_BASE_NOW, tz=timezone.utc)


def _stamp(offset_seconds: float) -> tuple[str, float]:
    """返回 (可读时间, epoch 秒)，相对导入时刻偏移，保证过期/有效语义稳定。"""
    moment = _BASE_DT + timedelta(seconds=offset_seconds)
    return moment.isoformat(), _BASE_NOW + offset_seconds

